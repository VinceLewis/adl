function mergeFieldReferences(
  left: Map<string, NamedReference<ExpressionFieldReference>>,
  right: Map<string, NamedReference<ExpressionFieldReference>>,
): Map<string, NamedReference<ExpressionFieldReference>> {
  const result = new Map(left);
  for (const [name, reference] of right) {
    if (!result.has(name)) {
      result.set(name, reference);
    }
  }
  return result;
}

function mergePresentationExpressionFields(
  fieldsByName: Map<string, NamedReference<ExpressionFieldReference>>,
  stateByName: Map<string, NamedReference<ResolvedPresentationState>>,
): Map<string, NamedReference<ExpressionFieldReference>> {
  const result = new Map(fieldsByName);
  for (const [name, state] of stateByName) {
    result.set(name, {
      item: expressionTypeField(name, state.item.type),
      index: state.index,
    });
  }
  return result;
}

function isValidIsoDate(value: string): boolean {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) {
    return false;
  }
  const date = new Date(`${value}T00:00:00.000Z`);
  return !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === value;
}

function isValidIsoMonthOrDate(value: string): boolean {
  if (/^\d{4}-\d{2}$/.test(value)) {
    return isValidIsoDate(`${value}-01`);
  }
  return isValidIsoDate(value);
}

function indexPresentationControls(
  sections: ResolvedPresentationSection[],
): Map<string, NamedReference<ResolvedPresentationControl>> {
  const controlsByName = new Map<string, NamedReference<ResolvedPresentationControl>>();
  let controlCount = 0;
  for (const section of sections) {
    for (const control of section.controls) {
      controlsByName.set(control.name, {
        item: control,
        index: controlCount,
      });
      controlCount += 1;
    }
  }
  return controlsByName;
}

function validateViewContext(
  context: ResolvedViewContext | undefined,
  contextPath: string,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  if (context === undefined) {
    return;
  }

  if (!VIEW_CONTEXT_MODES.has(context.mode)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.VIEW_CONTEXT_MODE_INVALID,
        `View has invalid context mode '${String(context.mode)}'.`,
        `${contextPath}.mode`,
      ),
    );
  }

  if (context.mode !== "none" && context.context === undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.VIEW_CONTEXT_REQUIRED,
        `View context mode '${String(context.mode)}' must reference a business context.`,
        `${contextPath}.context`,
      ),
    );
    return;
  }

  if (context.context !== undefined && !indexes.contextsByName.has(context.context)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.VIEW_CONTEXT_UNKNOWN,
        `View references unknown context '${context.context}'.`,
        `${contextPath}.context`,
      ),
    );
  }
}

function validateReadModel(
  readModel: ResolvedReadModel,
  readModelIndex: number,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  const readModelPath = `readModels[${readModelIndex}]`;
  const sourcesByName = indexByName(readModel.sources);

  validateReadModelContext(readModel.context, `${readModelPath}.context`, indexes, diagnostics);
  if (!READ_MODEL_STRATEGIES.has(readModel.strategy)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.READ_MODEL_STRATEGY_INVALID,
        `Read model '${readModel.name}' has invalid strategy '${String(readModel.strategy)}'.`,
        `${readModelPath}.strategy`,
      ),
    );
  }
  reportDuplicateNames(
    readModel.sources,
    `${readModelPath}.sources`,
    MODEL_VALIDATION_CODES.READ_MODEL_SOURCE_DUPLICATE,
    diagnostics,
    `Source names must be unique within read model '${readModel.name}'.`,
  );
  reportDuplicateNames(
    readModel.fields,
    `${readModelPath}.fields`,
    MODEL_VALIDATION_CODES.READ_MODEL_FIELD_DUPLICATE,
    diagnostics,
    `Output field names must be unique within read model '${readModel.name}'.`,
  );

  const earlierSourcesByName = new Map<string, ResolvedReadModelSource>();
  for (let sourceIndex = 0; sourceIndex < readModel.sources.length; sourceIndex += 1) {
    const source = readModel.sources[sourceIndex];
    if (source === undefined) {
      continue;
    }

    if (!READ_MODEL_SOURCE_SCOPES.has(source.scope)) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.READ_MODEL_SOURCE_SCOPE_INVALID,
          `Read model '${readModel.name}' source '${source.name}' has invalid scope '${String(source.scope)}'.`,
          `${readModelPath}.sources[${sourceIndex}].scope`,
        ),
      );
    }

    if (!indexes.objectsByName.has(source.object)) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.READ_MODEL_SOURCE_OBJECT_UNKNOWN,
          `Read model '${readModel.name}' source '${source.name}' references unknown object '${source.object}'.`,
          `${readModelPath}.sources[${sourceIndex}].object`,
        ),
      );
    }

    validateReadModelSourceJoin(
      source,
      sourceIndex === 0,
      readModel,
      `${readModelPath}.sources[${sourceIndex}]`,
      earlierSourcesByName,
      indexes,
      diagnostics,
    );

    earlierSourcesByName.set(source.name, source);
  }

  const fieldNames = new Set(readModel.fields.map((field) => field.name));
  for (let sortIndex = 0; sortIndex < readModel.sort.length; sortIndex += 1) {
    const sortItem = readModel.sort[sortIndex];
    if (sortItem === undefined) {
      continue;
    }
    if (!fieldNames.has(sortItem.field)) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.READ_MODEL_SORT_FIELD_UNKNOWN,
          `Read model '${readModel.name}' sorts by unknown output field '${sortItem.field}'.`,
          `${readModelPath}.sort[${sortIndex}].field`,
        ),
      );
    }
  }

  const projectedFieldsByName = new Map<string, NamedReference<ExpressionFieldReference>>();
  for (let fieldIndex = 0; fieldIndex < readModel.fields.length; fieldIndex += 1) {
    const field = readModel.fields[fieldIndex];
    if (field === undefined) {
      continue;
    }
    const fieldPath = `${readModelPath}.fields[${fieldIndex}]`;

    if (field.type !== undefined && !FIELD_TYPES.has(field.type)) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.READ_MODEL_FIELD_TYPE_INVALID,
          `Read model '${readModel.name}' output field '${field.name}' has invalid type '${String(field.type)}'.`,
          `${fieldPath}.type`,
        ),
      );
    }

    if (field.expression !== undefined) {
      if (field.source !== undefined || field.field !== undefined) {
        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.READ_MODEL_FIELD_SHAPE_INVALID,
            `Read model '${readModel.name}' expression field '${field.name}' cannot also project a source field.`,
            fieldPath,
          ),
        );
      }

      const expressionType = validateExpression(
        field.expression,
        `${fieldPath}.expression`,
        projectedFieldsByName,
        {
          invalid: MODEL_VALIDATION_CODES.READ_MODEL_FIELD_EXPRESSION_INVALID,
          field: MODEL_VALIDATION_CODES.READ_MODEL_FIELD_EXPRESSION_FIELD_UNKNOWN,
          runtime: MODEL_VALIDATION_CODES.READ_MODEL_FIELD_EXPRESSION_RUNTIME_PROPERTY_INVALID,
          type: MODEL_VALIDATION_CODES.READ_MODEL_FIELD_EXPRESSION_TYPE,
        },
        diagnostics,
      );

      if (
        field.type !== undefined &&
        expressionType !== "unknown" &&
        expressionType !== "null" &&
        expressionTypeToFieldType(expressionType) !== field.type
      ) {
        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.READ_MODEL_FIELD_EXPRESSION_TYPE,
            `Read model '${readModel.name}' expression field '${field.name}' declares ${field.type} but expression resolves to ${expressionType}.`,
            `${fieldPath}.expression`,
          ),
        );
      }

      projectedFieldsByName.set(field.name, {
        item: expressionTypeField(field.name, field.type ?? expressionType),
        index: fieldIndex,
      });
      continue;
    }

    if (field.field !== undefined && field.source === undefined) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.READ_MODEL_FIELD_SOURCE_UNKNOWN,
          `Read model '${readModel.name}' output field '${field.name}' must name a source before referencing field '${field.field}'.`,
          `${fieldPath}.source`,
        ),
      );
      continue;
    }

    if (field.source === undefined) {
      projectedFieldsByName.set(field.name, {
        item: expressionTypeField(field.name, field.type ?? "text"),
        index: fieldIndex,
      });
      continue;
    }

    const source = sourcesByName.get(field.source)?.item;
    if (source === undefined) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.READ_MODEL_FIELD_SOURCE_UNKNOWN,
          `Read model '${readModel.name}' output field '${field.name}' references unknown source '${field.source}'.`,
          `${fieldPath}.source`,
        ),
      );
      continue;
    }

    const sourceObject = indexes.objectsByName.get(source.object)?.item;
    if (sourceObject === undefined || field.field === undefined) {
      projectedFieldsByName.set(field.name, {
        item: expressionTypeField(field.name, field.type ?? "text"),
        index: fieldIndex,
      });
      continue;
    }

    const sourceFieldsByName = indexObjectExpressionFields(sourceObject);
    const sourceField = sourceFieldsByName.get(field.field)?.item;
    if (sourceField === undefined) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.READ_MODEL_FIELD_UNKNOWN,
          `Read model '${readModel.name}' output field '${field.name}' references unknown field '${field.field}' on source '${source.name}'.`,
          `${fieldPath}.field`,
        ),
      );
    }

    projectedFieldsByName.set(field.name, {
      item: expressionTypeField(field.name, field.type ?? sourceField?.type ?? "text"),
      index: fieldIndex,
    });
  }
}

/**
 * A join is only evaluable in one direction: the runtime walks the sources in
 * declaration order, so a source may only reach one it already has. Naming
 * itself or a later source would ask the runtime to key on rows it has not read,
 * which is the same forward-reference ban command steps carry, for the same
 * reason.
 */
function validateReadModelSourceJoin(
  source: ResolvedReadModelSource,
  isPrimarySource: boolean,
  readModel: ResolvedReadModel,
  sourcePath: string,
  earlierSourcesByName: Map<string, ResolvedReadModelSource>,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  const join = source.join;
  if (join === undefined) {
    return;
  }

  if (isPrimarySource) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.READ_MODEL_JOIN_PRIMARY_SOURCE_INVALID,
        `Read model '${readModel.name}' source '${source.name}' is the first source and has nothing to join onto.`,
        `${sourcePath}.join`,
      ),
    );
  }

  if (readModel.strategy === "union") {
    /*
     * A union interleaves independent feeds rather than widening one row, so
     * there is no upstream row for a join to key against. Accepting the
     * declaration would leave two plausible readings of the same model.
     */
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.READ_MODEL_JOIN_STRATEGY_INVALID,
        `Read model '${readModel.name}' uses the union strategy, so source '${source.name}' must not declare a join.`,
        `${sourcePath}.join`,
      ),
    );
  }

  if (!READ_MODEL_JOIN_CARDINALITIES.has(join.cardinality)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.READ_MODEL_JOIN_CARDINALITY_INVALID,
        `Read model '${readModel.name}' source '${source.name}' has invalid join cardinality '${String(join.cardinality)}'.`,
        `${sourcePath}.join.cardinality`,
      ),
    );
  }

  const joinedSource = earlierSourcesByName.get(join.source);
  if (joinedSource === undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.READ_MODEL_JOIN_SOURCE_UNKNOWN,
        `Read model '${readModel.name}' source '${source.name}' joins unknown or later source '${join.source}'.`,
        `${sourcePath}.join.source`,
      ),
    );
  }

  validateReadModelJoinField(
    join.localField,
    source,
    readModel,
    `${sourcePath}.join.localField`,
    indexes,
    diagnostics,
  );

  if (joinedSource !== undefined) {
    validateReadModelJoinField(
      join.sourceField,
      joinedSource,
      readModel,
      `${sourcePath}.join.sourceField`,
      indexes,
      diagnostics,
    );
  }
}

function validateReadModelJoinField(
  fieldName: string,
  source: ResolvedReadModelSource,
  readModel: ResolvedReadModel,
  fieldPath: string,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  // The record's own id is not a declared field, and requiring an object to
  // carry a duplicate of it would make every junction join say the same thing
  // twice.
  if (fieldName === RECORD_ID_JOIN_FIELD) {
    return;
  }

  const object = indexes.objectsByName.get(source.object)?.item;
  if (object === undefined) {
    // Already reported against the source itself.
    return;
  }

  if (indexObjectExpressionFields(object).has(fieldName)) {
    return;
  }

  diagnostics.push(
    diagnostic(
      MODEL_VALIDATION_CODES.READ_MODEL_JOIN_FIELD_UNKNOWN,
      `Read model '${readModel.name}' join references unknown field '${fieldName}' on source '${source.name}' object '${object.name}'.`,
      fieldPath,
    ),
  );
}

function validateDecisionTable(
  table: ResolvedDecisionTable,
  tableIndex: number,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  const tablePath = `decisionTables[${tableIndex}]`;
  const object = indexes.objectsByName.get(table.object)?.item;

  if (table.match !== "first" && table.match !== "single") {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.DECISION_TABLE_MATCH_INVALID,
        `Decision table '${table.name}' has invalid match policy '${String(table.match)}'.`,
        `${tablePath}.match`,
      ),
    );
  }

  reportDuplicateNames(
    table.inputs,
    `${tablePath}.inputs`,
    MODEL_VALIDATION_CODES.DECISION_TABLE_INPUT_DUPLICATE,
    diagnostics,
    `Input names must be unique within decision table '${table.name}'.`,
  );
  reportDuplicateNames(
    table.rows,
    `${tablePath}.rows`,
    MODEL_VALIDATION_CODES.DECISION_TABLE_ROW_DUPLICATE,
    diagnostics,
    `Row names must be unique within decision table '${table.name}'.`,
  );

  if (table.defaultOutputs === undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.DECISION_TABLE_DEFAULT_MISSING,
        `Decision table '${table.name}' must declare an explicit default output.`,
        `${tablePath}.defaultOutputs`,
      ),
    );
  }

  if (object === undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.DECISION_TABLE_OBJECT_UNKNOWN,
        `Decision table '${table.name}' references unknown object '${table.object}'.`,
        `${tablePath}.object`,
      ),
    );
    return;
  }

  const objectFieldsByName = indexByName(object.fields);
  const inputFields: ResolvedField[] = [];

  for (let inputIndex = 0; inputIndex < table.inputs.length; inputIndex += 1) {
    const input = table.inputs[inputIndex];
    if (input === undefined) {
      continue;
    }
    const inputType = validateExpression(
      input.expression,
      `${tablePath}.inputs[${inputIndex}].expression`,
      objectFieldsByName,
      {
        invalid: MODEL_VALIDATION_CODES.DECISION_TABLE_INPUT_INVALID,
        field: MODEL_VALIDATION_CODES.DECISION_TABLE_INPUT_FIELD_UNKNOWN,
        runtime: MODEL_VALIDATION_CODES.DECISION_TABLE_INPUT_RUNTIME_PROPERTY_INVALID,
        type: MODEL_VALIDATION_CODES.DECISION_TABLE_INPUT_INVALID,
      },
      diagnostics,
    );
    inputFields.push(expressionTypeField(input.name, inputType));
  }

  const inputFieldsByName = indexByName(inputFields);
  const analyzedRows: DecisionTableAnalyzedRow[] = [];

  for (let rowIndex = 0; rowIndex < table.rows.length; rowIndex += 1) {
    const row = table.rows[rowIndex];
    if (row === undefined) {
      continue;
    }
    const rowPath = `${tablePath}.rows[${rowIndex}]`;
    const rowType = validateExpression(
      row.condition,
      `${rowPath}.condition`,
      inputFieldsByName,
      {
        invalid: MODEL_VALIDATION_CODES.DECISION_TABLE_ROW_CONDITION_INVALID,
        field: MODEL_VALIDATION_CODES.DECISION_TABLE_ROW_CONDITION_FIELD_UNKNOWN,
        runtime: MODEL_VALIDATION_CODES.DECISION_TABLE_ROW_CONDITION_RUNTIME_PROPERTY_INVALID,
        type: MODEL_VALIDATION_CODES.DECISION_TABLE_ROW_CONDITION_TYPE,
      },
      diagnostics,
    );
    if (rowType !== "boolean" && rowType !== "unknown") {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.DECISION_TABLE_ROW_CONDITION_TYPE,
          `Decision table '${table.name}' row '${row.name}' condition must resolve to boolean, not ${rowType}.`,
          `${rowPath}.condition`,
        ),
      );
    }

    const analyzed = analyzeDecisionTableRow(row, rowPath, diagnostics);
    analyzedRows.push({ row, rowIndex, rowPath, analysis: analyzed });
  }

  analyzeDecisionTableRows(table, analyzedRows, diagnostics);
}

interface DecisionTableAnalyzedRow {
  row: ResolvedDecisionTableRow;
  rowIndex: number;
  rowPath: string;
  analysis: DecisionTableAnalysis;
}

interface DecisionTableAnalysis {
  analyzable: boolean;
  impossible: boolean;
  constraints: Map<string, DecisionConstraint>;
}

type DecisionConstraint =
  | { kind: "any" }
  | { kind: "never" }
  | {
      kind: "range";
      exact?: string | number | boolean | null;
      min?: number;
      minInclusive?: boolean;
      max?: number;
      maxInclusive?: boolean;
    };

function analyzeDecisionTableRow(
  row: ResolvedDecisionTableRow,
  rowPath: string,
  diagnostics: Diagnostic[],
): DecisionTableAnalysis {
  const analysis = analyzeDecisionExpression(row.condition);
  if (!analysis.analyzable) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.DECISION_TABLE_ROW_CONDITION_UNANALYZABLE,
        `Decision table row '${row.name}' condition is valid at runtime but outside the compile-time analyzable subset.`,
        `${rowPath}.condition`,
        "warning",
      ),
    );
  }
  if (analysis.impossible) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.DECISION_TABLE_ROW_UNREACHABLE,
        `Decision table row '${row.name}' cannot match because its condition is contradictory.`,
        `${rowPath}.condition`,
        "warning",
      ),
    );
  }
  return analysis;
}

function analyzeDecisionTableRows(
  table: ResolvedDecisionTable,
  rows: DecisionTableAnalyzedRow[],
  diagnostics: Diagnostic[],
): void {
  const analyzableRows = rows.filter((row) => row.analysis.analyzable && !row.analysis.impossible);

  for (let rowIndex = 0; rowIndex < analyzableRows.length; rowIndex += 1) {
    const row = analyzableRows[rowIndex];
    if (row === undefined) {
      continue;
    }

    for (let previousIndex = 0; previousIndex < rowIndex; previousIndex += 1) {
      const previous = analyzableRows[previousIndex];
      if (previous === undefined) {
        continue;
      }

      if (constraintsOverlap(previous.analysis.constraints, row.analysis.constraints)) {
        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.DECISION_TABLE_ROW_OVERLAP,
            `Decision table '${table.name}' row '${row.row.name}' overlaps earlier row '${previous.row.name}'.`,
            `${row.rowPath}.condition`,
            table.match === "single" ? "error" : "warning",
          ),
        );
      }

      if (constraintsSubsume(previous.analysis.constraints, row.analysis.constraints)) {
        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.DECISION_TABLE_ROW_UNREACHABLE,
            `Decision table '${table.name}' row '${row.row.name}' is unreachable because earlier row '${previous.row.name}' matches all of its cases.`,
            `${row.rowPath}.condition`,
            "warning",
          ),
        );
        break;
      }
    }
  }
}

function analyzeDecisionExpression(expression: ResolvedExpression): DecisionTableAnalysis {
  if (expression.kind === "literal") {
    if (expression.value === true) {
      return { analyzable: true, impossible: false, constraints: new Map() };
    }
    if (expression.value === false) {
      return { analyzable: true, impossible: true, constraints: new Map() };
    }
    return { analyzable: false, impossible: false, constraints: new Map() };
  }

  if (expression.kind === "binary" && expression.operator === "and") {
    return mergeDecisionAnalyses(
      analyzeDecisionExpression(expression.left),
      analyzeDecisionExpression(expression.right),
    );
  }

  if (expression.kind === "binary") {
    return analyzeDecisionComparison(expression);
  }

  return { analyzable: false, impossible: false, constraints: new Map() };
}

function analyzeDecisionComparison(
  expression: Extract<ResolvedExpression, { kind: "binary" }>,
): DecisionTableAnalysis {
  if (expression.left.kind === "field" && expression.right.kind === "literal") {
    const constraint = constraintForOperator(expression.operator, expression.right.value, false);
    return constraint === undefined
      ? { analyzable: false, impossible: false, constraints: new Map() }
      : {
          analyzable: true,
          impossible: false,
          constraints: new Map([[expression.left.field, constraint]]),
        };
  }

  if (expression.right.kind === "field" && expression.left.kind === "literal") {
    const constraint = constraintForOperator(expression.operator, expression.left.value, true);
    return constraint === undefined
      ? { analyzable: false, impossible: false, constraints: new Map() }
      : {
          analyzable: true,
          impossible: false,
          constraints: new Map([[expression.right.field, constraint]]),
        };
  }

  return { analyzable: false, impossible: false, constraints: new Map() };
}

function constraintForOperator(
  operator: string,
  literal: string | number | boolean | null,
  reversed: boolean,
): DecisionConstraint | undefined {
  if (operator === "==") {
    return { kind: "range", exact: literal };
  }

  if (typeof literal !== "number") {
    return undefined;
  }

  switch (reverseComparisonOperator(operator, reversed)) {
    case ">":
      return { kind: "range", min: literal, minInclusive: false };
    case ">=":
      return { kind: "range", min: literal, minInclusive: true };
    case "<":
      return { kind: "range", max: literal, maxInclusive: false };
    case "<=":
      return { kind: "range", max: literal, maxInclusive: true };
    default:
      return undefined;
  }
}

function reverseComparisonOperator(operator: string, reversed: boolean): string {
  if (!reversed) {
    return operator;
  }
  switch (operator) {
    case ">":
      return "<";
    case ">=":
      return "<=";
    case "<":
      return ">";
    case "<=":
      return ">=";
    default:
      return operator;
  }
}

function mergeDecisionAnalyses(
  left: DecisionTableAnalysis,
  right: DecisionTableAnalysis,
): DecisionTableAnalysis {
  const constraints = new Map(left.constraints);
  let impossible = left.impossible || right.impossible;

  for (const [field, rightConstraint] of right.constraints) {
    const merged = intersectConstraint(constraints.get(field) ?? { kind: "any" }, rightConstraint);
    constraints.set(field, merged);
    impossible = impossible || merged.kind === "never";
  }

  return {
    analyzable: left.analyzable && right.analyzable,
    impossible,
    constraints,
  };
}

function intersectConstraint(
  left: DecisionConstraint,
  right: DecisionConstraint,
): DecisionConstraint {
  if (left.kind === "never" || right.kind === "never") {
    return { kind: "never" };
  }
  if (left.kind === "any") {
    return right;
  }
  if (right.kind === "any") {
    return left;
  }
  if (left.exact !== undefined && right.exact !== undefined) {
    return left.exact === right.exact ? left : { kind: "never" };
  }
  if (left.exact !== undefined) {
    return exactFitsRange(left.exact, right) ? left : { kind: "never" };
  }
  if (right.exact !== undefined) {
    return exactFitsRange(right.exact, left) ? right : { kind: "never" };
  }

  const min = stricterMin(left, right);
  const max = stricterMax(left, right);
  const merged = rangeConstraint(min, max);
  return rangeIsContradictory(merged) ? { kind: "never" } : merged;
}

function constraintsOverlap(
  left: Map<string, DecisionConstraint>,
  right: Map<string, DecisionConstraint>,
): boolean {
  for (const field of new Set([...left.keys(), ...right.keys()])) {
    if (
      !constraintOverlap(left.get(field) ?? { kind: "any" }, right.get(field) ?? { kind: "any" })
    ) {
      return false;
    }
  }
  return true;
}

function constraintsSubsume(
  possibleSuperset: Map<string, DecisionConstraint>,
  possibleSubset: Map<string, DecisionConstraint>,
): boolean {
  for (const field of new Set([...possibleSuperset.keys(), ...possibleSubset.keys()])) {
    if (
      !constraintSubsumes(
        possibleSuperset.get(field) ?? { kind: "any" },
        possibleSubset.get(field) ?? { kind: "any" },
      )
    ) {
      return false;
    }
  }
  return true;
}

function constraintOverlap(left: DecisionConstraint, right: DecisionConstraint): boolean {
  return intersectConstraint(left, right).kind !== "never";
}

function constraintSubsumes(superset: DecisionConstraint, subset: DecisionConstraint): boolean {
  if (superset.kind === "any" || subset.kind === "never") {
    return true;
  }
  if (superset.kind === "never") {
    return false;
  }
  if (subset.kind === "any") {
    return false;
  }
  if (subset.exact !== undefined) {
    return superset.exact !== undefined
      ? superset.exact === subset.exact
      : exactFitsRange(subset.exact, superset);
  }
  if (superset.exact !== undefined) {
    return false;
  }
  return rangeContainsRange(superset, subset);
}

function exactFitsRange(
  exact: string | number | boolean | null,
  range: DecisionConstraint,
): boolean {
  if (range.kind !== "range") {
    return range.kind === "any";
  }
  if (range.exact !== undefined) {
    return range.exact === exact;
  }
  if (typeof exact !== "number") {
    return range.min === undefined && range.max === undefined;
  }
  if (
    range.min !== undefined &&
    (exact < range.min || (exact === range.min && !range.minInclusive))
  ) {
    return false;
  }
  if (
    range.max !== undefined &&
    (exact > range.max || (exact === range.max && !range.maxInclusive))
  ) {
    return false;
  }
  return true;
}

function rangeContainsRange(superset: DecisionConstraint, subset: DecisionConstraint): boolean {
  if (superset.kind !== "range" || subset.kind !== "range") {
    return false;
  }
  const minOk =
    superset.min === undefined ||
    (subset.min !== undefined &&
      (subset.min > superset.min ||
        (subset.min === superset.min &&
          (Boolean(subset.minInclusive) || !Boolean(superset.minInclusive)))));
  const maxOk =
    superset.max === undefined ||
    (subset.max !== undefined &&
      (subset.max < superset.max ||
        (subset.max === superset.max &&
          (Boolean(subset.maxInclusive) || !Boolean(superset.maxInclusive)))));
  return minOk && maxOk;
}

function rangeConstraint(
  min: { value: number | undefined; inclusive: boolean | undefined },
  max: { value: number | undefined; inclusive: boolean | undefined },
): DecisionConstraint {
  return {
    kind: "range",
    ...(min.value === undefined
      ? {}
      : {
          min: min.value,
          ...(min.inclusive === undefined ? {} : { minInclusive: min.inclusive }),
        }),
    ...(max.value === undefined
      ? {}
      : {
          max: max.value,
          ...(max.inclusive === undefined ? {} : { maxInclusive: max.inclusive }),
        }),
  };
}

function stricterMin(
  left: DecisionConstraint,
  right: DecisionConstraint,
): { value: number | undefined; inclusive: boolean | undefined } {
  const leftMin = left.kind === "range" ? left.min : undefined;
  const rightMin = right.kind === "range" ? right.min : undefined;
  if (leftMin === undefined) {
    return { value: rightMin, inclusive: right.kind === "range" ? right.minInclusive : undefined };
  }
  if (rightMin === undefined) {
    return { value: leftMin, inclusive: left.kind === "range" ? left.minInclusive : undefined };
  }
  if (leftMin > rightMin) {
    return { value: leftMin, inclusive: left.kind === "range" ? left.minInclusive : undefined };
  }
  if (rightMin > leftMin) {
    return { value: rightMin, inclusive: right.kind === "range" ? right.minInclusive : undefined };
  }
  return {
    value: leftMin,
    inclusive:
      Boolean(left.kind === "range" && left.minInclusive) &&
      Boolean(right.kind === "range" && right.minInclusive),
  };
}

function stricterMax(
  left: DecisionConstraint,
  right: DecisionConstraint,
): { value: number | undefined; inclusive: boolean | undefined } {
  const leftMax = left.kind === "range" ? left.max : undefined;
  const rightMax = right.kind === "range" ? right.max : undefined;
  if (leftMax === undefined) {
    return { value: rightMax, inclusive: right.kind === "range" ? right.maxInclusive : undefined };
  }
  if (rightMax === undefined) {
    return { value: leftMax, inclusive: left.kind === "range" ? left.maxInclusive : undefined };
  }
  if (leftMax < rightMax) {
    return { value: leftMax, inclusive: left.kind === "range" ? left.maxInclusive : undefined };
  }
  if (rightMax < leftMax) {
    return { value: rightMax, inclusive: right.kind === "range" ? right.maxInclusive : undefined };
  }
  return {
    value: leftMax,
    inclusive:
      Boolean(left.kind === "range" && left.maxInclusive) &&
      Boolean(right.kind === "range" && right.maxInclusive),
  };
}

function rangeIsContradictory(range: DecisionConstraint): boolean {
  if (range.kind !== "range" || range.min === undefined || range.max === undefined) {
    return false;
  }
  return (
    range.min > range.max ||
    (range.min === range.max && (!range.minInclusive || !range.maxInclusive))
  );
}

function validateCommand(
  command: ResolvedCommand,
  commandIndex: number,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  const commandPath = `commands[${commandIndex}]`;
  const inputsByName = indexByName(command.inputs);
  const inputFieldsByName = commandInputFieldsByName(command.inputs);
  const previousStepsByName = new Map<string, ResolvedCommandStep>();

  reportDuplicateNames(
    command.inputs,
    `${commandPath}.inputs`,
    MODEL_VALIDATION_CODES.COMMAND_INPUT_DUPLICATE,
    diagnostics,
    `Input names must be unique within command '${command.name}'.`,
  );
  reportDuplicateNames(
    command.steps,
    `${commandPath}.steps`,
    MODEL_VALIDATION_CODES.COMMAND_STEP_DUPLICATE,
    diagnostics,
    `Step names must be unique within command '${command.name}'.`,
  );

  for (let inputIndex = 0; inputIndex < command.inputs.length; inputIndex += 1) {
    const input = command.inputs[inputIndex];
    if (input === undefined) {
      continue;
    }
    validateCommandInput(input, `${commandPath}.inputs[${inputIndex}]`, command, diagnostics);
  }

  for (
    let preconditionIndex = 0;
    preconditionIndex < command.preconditions.length;
    preconditionIndex += 1
  ) {
    const precondition = command.preconditions[preconditionIndex];
    if (precondition === undefined) {
      continue;
    }
    validateCommandPrecondition(
      precondition,
      `${commandPath}.preconditions[${preconditionIndex}]`,
      command,
      inputFieldsByName,
      diagnostics,
    );
  }

  for (let stepIndex = 0; stepIndex < command.steps.length; stepIndex += 1) {
    const step = command.steps[stepIndex];
    if (step === undefined) {
      continue;
    }
    validateCommandStep(
      step,
      `${commandPath}.steps[${stepIndex}]`,
      command,
      inputsByName,
      previousStepsByName,
      indexes,
      diagnostics,
    );
    previousStepsByName.set(step.name, step);
  }

  validateCommandStepSyncCoherence(command, commandPath, indexes, diagnostics);
}

/**
 * A command replays to the authority as a single `command` intent, and a queue
 * entry carries exactly one object's sync declaration. So if a command's steps
 * disagree about whether their writes are delivered to the authority at all,
 * there is no delivery the runtime can choose that is not wrong: queue the
 * command and the authority refuses the write that was never meant to leave the
 * device, on this reconnect and on every one after it; withhold it and the steps
 * that were meant to reach the authority silently never do. Refusing the model
 * is the only answer that does not lose writes or wedge the queue.
 *
 * Mixing `localFirst` with `onlineRequired` is not this defect. Both queue, and
 * `commandModeRank` in the object store picks the more demanding of the two to
 * file the entry under. A command all of whose objects withhold their writes is
 * not this defect either: it simply never enters the queue.
 */
function validateCommandStepSyncCoherence(
  command: ResolvedCommand,
  commandPath: string,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  const queued = new Map<string, SyncMode>();
  const withheld = new Map<string, SyncMode>();

  for (let stepIndex = 0; stepIndex < command.steps.length; stepIndex += 1) {
    const step = command.steps[stepIndex];
    if (step === undefined) {
      continue;
    }
    const object = indexes.objectsByName.get(step.object)?.item;
    if (object === undefined) {
      // Already reported as an unknown step object, and an object that does not
      // resolve has no declared mode to disagree with.
      continue;
    }
    const mode = object.sync.mode;
    if (!SYNC_MODES.has(mode)) {
      // Same reasoning for an unreadable mode: it is already reported against
      // the object, and guessing which side of the split it belongs on would
      // stack a second, misleading error on top of the first.
      continue;
    }
    (isQueueableSyncMode(mode) ? queued : withheld).set(object.name, mode);
  }

  if (queued.size === 0 || withheld.size === 0) {
    return;
  }

  // One diagnostic for the whole command: the disagreement is a property of the
  // command, and no single step is the one at fault.
  diagnostics.push(
    diagnostic(
      MODEL_VALIDATION_CODES.COMMAND_STEP_SYNC_MODE_MIXED,
      `Command '${command.name}' replays to the authority as one transaction, so its steps cannot disagree about whether their writes are delivered to the authority at all. Steps write ${describeObjectSyncModes(queued)}, whose writes are queued for the authority, and ${describeObjectSyncModes(withheld)}, whose writes never leave the device.`,
      `${commandPath}.steps`,
    ),
  );
}

function describeObjectSyncModes(modesByObject: Map<string, SyncMode>): string {
  return [...modesByObject].map(([objectName, mode]) => `'${objectName}' (${mode})`).join(", ");
}

function validateCommandInput(
  input: ResolvedCommandInput,
  inputPath: string,
  command: ResolvedCommand,
  diagnostics: Diagnostic[],
): void {
  if (!FIELD_TYPES.has(input.type)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.COMMAND_INPUT_TYPE_INVALID,
        `Command '${command.name}' input '${input.name}' has invalid type '${String(input.type)}'.`,
        `${inputPath}.type`,
      ),
    );
  }

  if (input.repeated && input.defaultValue !== undefined) {
    /*
     * A default is one value and a repeated input carries a list, so there is
     * no reading of a declared default that is not either a silently wrapped
     * single-item list or a silently ignored declaration.
     */
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.COMMAND_INPUT_REPEATED_DEFAULT_INVALID,
        `Command '${command.name}' input '${input.name}' is repeated, so it must not declare a default value.`,
        `${inputPath}.defaultValue`,
      ),
    );
  } else if (
    input.defaultValue !== undefined &&
    !isValueCompatibleWithFieldType(input.type, input.defaultValue)
  ) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.COMMAND_INPUT_DEFAULT_INCOMPATIBLE,
        `Default value for command '${command.name}' input '${input.name}' is not compatible with ${input.type}.`,
        `${inputPath}.defaultValue`,
      ),
    );
  }

  if (!input.repeated && input.itemFields.length > 0) {
    // Item fields describe the shape of one element of a list. A single-valued
    // input has no elements, so the declaration would never be read.
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.COMMAND_INPUT_ITEM_FIELDS_INVALID,
        `Command '${command.name}' input '${input.name}' declares item fields but is not repeated.`,
        `${inputPath}.itemFields`,
      ),
    );
  }

  reportDuplicateNames(
    input.itemFields,
    `${inputPath}.itemFields`,
    MODEL_VALIDATION_CODES.COMMAND_INPUT_ITEM_FIELD_DUPLICATE,
    diagnostics,
    `Item field names must be unique within command '${command.name}' input '${input.name}'.`,
  );

  for (let itemFieldIndex = 0; itemFieldIndex < input.itemFields.length; itemFieldIndex += 1) {
    const itemField = input.itemFields[itemFieldIndex];
    if (itemField === undefined) {
      continue;
    }
    if (!FIELD_TYPES.has(itemField.type)) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.COMMAND_INPUT_ITEM_FIELD_TYPE_INVALID,
          `Command '${command.name}' input '${input.name}' item field '${itemField.name}' has invalid type '${String(itemField.type)}'.`,
          `${inputPath}.itemFields[${itemFieldIndex}].type`,
        ),
      );
    }
  }
}

function validateCommandPrecondition(
  precondition: ResolvedCommandPrecondition,
  preconditionPath: string,
  command: ResolvedCommand,
  inputFieldsByName: Map<string, NamedReference<ResolvedField>>,
  diagnostics: Diagnostic[],
): void {
  const preconditionType = validateExpression(
    precondition.expression,
    `${preconditionPath}.expression`,
    inputFieldsByName,
    {
      invalid: MODEL_VALIDATION_CODES.COMMAND_PRECONDITION_INVALID,
      field: MODEL_VALIDATION_CODES.COMMAND_PRECONDITION_FIELD_UNKNOWN,
      runtime: MODEL_VALIDATION_CODES.COMMAND_PRECONDITION_RUNTIME_PROPERTY_INVALID,
      type: MODEL_VALIDATION_CODES.COMMAND_PRECONDITION_INVALID,
    },
    diagnostics,
  );

  if (preconditionType !== "boolean" && preconditionType !== "unknown") {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.COMMAND_PRECONDITION_INVALID,
        `Command '${command.name}' precondition '${precondition.name}' must resolve to boolean, not ${preconditionType}.`,
        `${preconditionPath}.expression`,
      ),
    );
  }
}

function validateCommandStep(
  step: ResolvedCommandStep,
  stepPath: string,
  command: ResolvedCommand,
  inputsByName: Map<string, NamedReference<ResolvedCommandInput>>,
  previousStepsByName: Map<string, ResolvedCommandStep>,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  const rawStep = step as { name?: string; action?: unknown };
  if (step.action !== "create" && step.action !== "update") {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.COMMAND_STEP_ACTION_INVALID,
        `Command '${command.name}' step '${rawStep.name ?? "<unnamed>"}' has invalid action '${String(rawStep.action)}'.`,
        `${stepPath}.action`,
      ),
    );
    return;
  }

  if (!COMMAND_STEP_AUTHORITIES.has(step.authority)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.COMMAND_AUTHORITY_INVALID,
        `Command '${command.name}' step '${step.name}' has invalid authority '${String(step.authority)}'.`,
        `${stepPath}.authority`,
      ),
    );
  }

  const iteration = validateCommandStepIteration(
    step,
    stepPath,
    command,
    inputsByName,
    diagnostics,
  );

  if (step.action === "create" && step.establishesContext !== undefined) {
    const establishedContext = indexes.contextsByName.get(step.establishesContext)?.item;
    if (establishedContext === undefined) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.COMMAND_STEP_CONTEXT_UNKNOWN,
          `Command '${command.name}' step '${step.name}' establishes unknown business context '${step.establishesContext}'.`,
          `${stepPath}.establishesContext`,
        ),
      );
    } else if (establishedContext.object !== step.object) {
      /*
       * The step puts *its own new record* in reach for the rest of the
       * transaction. If the record is not an instance of the context's object,
       * there is no instance to put in reach, and the declaration would either
       * do nothing or reach a context instance the caller did not create.
       */
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.COMMAND_STEP_CONTEXT_OBJECT_MISMATCH,
          `Command '${command.name}' step '${step.name}' establishes business context '${step.establishesContext}', whose object is '${establishedContext.object}', but the step creates '${step.object}'.`,
          `${stepPath}.establishesContext`,
        ),
      );
    }
  }

  const object = indexes.objectsByName.get(step.object)?.item;
  if (object === undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.COMMAND_STEP_OBJECT_UNKNOWN,
        `Command '${command.name}' step '${step.name}' references unknown object '${step.object}'.`,
        `${stepPath}.object`,
      ),
    );
    return;
  }

  const fieldsByName = indexByName(object.fields);
  const values = step.action === "create" ? step.values : step.patch;
  const valuesProperty = step.action === "create" ? "values" : "patch";

  for (const [fieldName, expression] of Object.entries(values)) {
    if (!fieldsByName.has(fieldName)) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.COMMAND_STEP_FIELD_UNKNOWN,
          `Command '${command.name}' step '${step.name}' references unknown field '${fieldName}' on object '${object.name}'.`,
          `${stepPath}.${valuesProperty}.${fieldName}`,
        ),
      );
    }

    validateCommandValueExpression(
      expression,
      `${stepPath}.${valuesProperty}.${fieldName}`,
      command,
      inputsByName,
      previousStepsByName,
      iteration,
      indexes,
      diagnostics,
    );
  }

  if (step.action === "update") {
    validateCommandValueExpression(
      step.recordId,
      `${stepPath}.recordId`,
      command,
      inputsByName,
      previousStepsByName,
      iteration,
      indexes,
      diagnostics,
    );
  }

  for (
    let preconditionIndex = 0;
    preconditionIndex < step.preconditions.length;
    preconditionIndex += 1
  ) {
    const precondition = step.preconditions[preconditionIndex];
    if (precondition === undefined) {
      continue;
    }
    const preconditionType = validateExpression(
      precondition,
      `${stepPath}.preconditions[${preconditionIndex}]`,
      fieldsByName,
      {
        invalid: MODEL_VALIDATION_CODES.COMMAND_PRECONDITION_INVALID,
        field: MODEL_VALIDATION_CODES.COMMAND_PRECONDITION_FIELD_UNKNOWN,
        runtime: MODEL_VALIDATION_CODES.COMMAND_PRECONDITION_RUNTIME_PROPERTY_INVALID,
        type: MODEL_VALIDATION_CODES.COMMAND_PRECONDITION_INVALID,
      },
      diagnostics,
    );
    if (preconditionType !== "boolean" && preconditionType !== "unknown") {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.COMMAND_PRECONDITION_INVALID,
          `Command '${command.name}' step '${step.name}' precondition must resolve to boolean, not ${preconditionType}.`,
          `${stepPath}.preconditions[${preconditionIndex}]`,
        ),
      );
    }
  }
}

/**
 * What a step's value expressions are allowed to say about iteration.
 *
 * `iterates` is whether the step declared `forEach` at all, which is what
 * decides whether `item` and `itemIndex` mean anything. `input` is the declared
 * repeated input when it resolved, which is what `item.field` is checked
 * against; it stays undefined when `forEach` itself was already reported, so a
 * single mistake produces a single diagnostic.
 */
interface CommandStepIteration {
  iterates: boolean;
  input?: ResolvedCommandInput;
}

function validateCommandStepIteration(
  step: ResolvedCommandStep,
  stepPath: string,
  command: ResolvedCommand,
  inputsByName: Map<string, NamedReference<ResolvedCommandInput>>,
  diagnostics: Diagnostic[],
): CommandStepIteration {
  if (step.forEach === undefined) {
    return { iterates: false };
  }

  const input = inputsByName.get(step.forEach)?.item;

  if (input === undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.COMMAND_STEP_FOR_EACH_UNKNOWN,
        `Command '${command.name}' step '${step.name}' iterates unknown input '${step.forEach}'.`,
        `${stepPath}.forEach`,
      ),
    );
    return { iterates: true };
  }

  if (!input.repeated) {
    // A single-valued input has one value, so "one write per item" has no
    // meaning; the step would silently become an ordinary single write.
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.COMMAND_STEP_FOR_EACH_NOT_REPEATED,
        `Command '${command.name}' step '${step.name}' iterates input '${step.forEach}', which is not repeated.`,
        `${stepPath}.forEach`,
      ),
    );
    return { iterates: true };
  }

  return { iterates: true, input };
}

function validateCommandValueExpression(
  expression: ResolvedCommandValueExpression,
  expressionPath: string,
  command: ResolvedCommand,
  inputsByName: Map<string, NamedReference<ResolvedCommandInput>>,
  previousStepsByName: Map<string, ResolvedCommandStep>,
  iteration: CommandStepIteration,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  switch (expression.kind) {
    case "literal":
      return;
    case "input":
      if (!inputsByName.has(expression.name)) {
        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.COMMAND_STEP_INPUT_UNKNOWN,
            `Command '${command.name}' expression references unknown input '${expression.name}'.`,
            `${expressionPath}.name`,
          ),
        );
      }
      return;
    case "runtime":
      if (!COMMAND_RUNTIME_PROPERTIES.has(expression.property)) {
        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.COMMAND_STEP_RUNTIME_PROPERTY_INVALID,
            `Command '${command.name}' expression references unsupported runtime property '${String(expression.property)}'.`,
            `${expressionPath}.property`,
          ),
        );
      }
      return;
    case "stepField": {
      const step = previousStepsByName.get(expression.step);
      if (step === undefined) {
        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.COMMAND_STEP_REFERENCE_UNKNOWN,
            `Command '${command.name}' expression references unknown or later step '${expression.step}'.`,
            `${expressionPath}.step`,
          ),
        );
        return;
      }

      reportIteratingStepReference(step, expressionPath, command, diagnostics);

      const object = indexes.objectsByName.get(step.object)?.item;
      if (object !== undefined && !object.fields.some((field) => field.name === expression.field)) {
        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.COMMAND_STEP_FIELD_UNKNOWN,
            `Command '${command.name}' expression references unknown field '${expression.field}' on step '${expression.step}'.`,
            `${expressionPath}.field`,
          ),
        );
      }
      return;
    }
    case "stepMeta": {
      const step = previousStepsByName.get(expression.step);
      if (step === undefined) {
        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.COMMAND_STEP_REFERENCE_UNKNOWN,
            `Command '${command.name}' expression references unknown or later step '${expression.step}'.`,
            `${expressionPath}.step`,
          ),
        );
      } else {
        reportIteratingStepReference(step, expressionPath, command, diagnostics);
      }
      if (!COMMAND_STEP_META_PROPERTIES.has(expression.property)) {
        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.COMMAND_STEP_META_PROPERTY_INVALID,
            `Command '${command.name}' expression references unsupported step metadata property '${String(expression.property)}'.`,
            `${expressionPath}.property`,
          ),
        );
      }
      return;
    }
    case "item": {
      if (!iteration.iterates) {
        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.COMMAND_STEP_ITEM_OUTSIDE_FOR_EACH,
            `Command '${command.name}' expression references the current item, but the step does not iterate an input.`,
            `${expressionPath}.kind`,
          ),
        );
        return;
      }

      const input = iteration.input;
      if (input === undefined) {
        // The iterated input itself was already reported; naming a field of an
        // item whose shape is unknown adds nothing.
        return;
      }

      if (input.itemFields.length === 0) {
        if (expression.field !== undefined) {
          diagnostics.push(
            diagnostic(
              MODEL_VALIDATION_CODES.COMMAND_STEP_ITEM_FIELD_UNKNOWN,
              `Command '${command.name}' expression reads item field '${expression.field}', but input '${input.name}' carries plain ${input.type} values and its items have no fields.`,
              `${expressionPath}.field`,
            ),
          );
        }
        return;
      }

      if (
        expression.field !== undefined &&
        !input.itemFields.some((itemField) => itemField.name === expression.field)
      ) {
        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.COMMAND_STEP_ITEM_FIELD_UNKNOWN,
            `Command '${command.name}' expression reads unknown item field '${expression.field}' of input '${input.name}'.`,
            `${expressionPath}.field`,
          ),
        );
      }
      return;
    }
    case "itemIndex":
      if (!iteration.iterates) {
        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.COMMAND_STEP_ITEM_OUTSIDE_FOR_EACH,
            `Command '${command.name}' expression references the current item index, but the step does not iterate an input.`,
            `${expressionPath}.kind`,
          ),
        );
      }
      return;
  }

  diagnostics.push(
    diagnostic(
      MODEL_VALIDATION_CODES.COMMAND_PRECONDITION_INVALID,
      `Command '${command.name}' expression has invalid kind '${String((expression as { kind?: unknown }).kind)}'.`,
      `${expressionPath}.kind`,
    ),
  );
}

/**
 * An iterating step writes one record per item, so "the record step X created"
 * names a set rather than a record. There is no single answer for a later step
 * to read, and picking one — the first, the last — would be a runtime invention
 * the model never asked for.
 */
function reportIteratingStepReference(
  step: ResolvedCommandStep,
  expressionPath: string,
  command: ResolvedCommand,
  diagnostics: Diagnostic[],
): void {
  if (step.forEach === undefined) {
    return;
  }

  diagnostics.push(
    diagnostic(
      MODEL_VALIDATION_CODES.COMMAND_STEP_ITERATING_REFERENCE,
      `Command '${command.name}' expression references step '${step.name}', which iterates input '${step.forEach}' and so produces many records rather than one.`,
      `${expressionPath}.step`,
    ),
  );
}

function validateReadModelContext(
  context: ResolvedViewContext | undefined,
  contextPath: string,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  if (context === undefined) {
    return;
  }

  if (!VIEW_CONTEXT_MODES.has(context.mode)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.READ_MODEL_CONTEXT_MODE_INVALID,
        `Read model has invalid context mode '${String(context.mode)}'.`,
        `${contextPath}.mode`,
      ),
    );
  }

  if (context.mode !== "none" && context.context === undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.READ_MODEL_CONTEXT_REQUIRED,
        `Read model context mode '${String(context.mode)}' must reference a business context.`,
        `${contextPath}.context`,
      ),
    );
    return;
  }

  if (context.context !== undefined && !indexes.contextsByName.has(context.context)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.READ_MODEL_CONTEXT_UNKNOWN,
        `Read model references unknown context '${context.context}'.`,
        `${contextPath}.context`,
      ),
    );
  }
}

function validateTheme(
  theme: ResolvedTheme,
  themeIndex: number,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  const themePath = `themes[${themeIndex}]`;

  if (theme.base !== undefined) {
    if (theme.base === theme.name) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.THEME_BASE_SELF_REFERENCE,
          `Theme '${theme.name}' cannot use itself as its base theme.`,
          `${themePath}.base`,
        ),
      );
    } else if (!indexes.themesByName.has(theme.base)) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.THEME_BASE_UNKNOWN,
          `Theme '${theme.name}' references unknown base theme '${theme.base}'.`,
          `${themePath}.base`,
        ),
      );
    }
  }

  const baseCycle = findThemeBaseCycle(theme, indexes);
  if (baseCycle !== undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.THEME_BASE_CYCLE,
        `Theme '${theme.name}' has a base theme cycle: ${baseCycle.join(" -> ")}.`,
        `${themePath}.base`,
      ),
    );
  }

  for (const tokenName of THEME_STRING_TOKENS) {
    const token = theme.tokens[tokenName];
    if (token !== undefined && (typeof token !== "string" || token.trim().length === 0)) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.THEME_TOKEN_INVALID,
          `Theme '${theme.name}' has invalid ${tokenName} token '${String(token)}'.`,
          `${themePath}.tokens.${tokenName}`,
        ),
      );
    }
  }

  if (!THEME_RADIUS_VALUES.has(theme.tokens.radius)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.THEME_TOKEN_INVALID,
        `Theme '${theme.name}' has invalid radius token '${String(theme.tokens.radius)}'.`,
        `${themePath}.tokens.radius`,
      ),
    );
  }

  if (!THEME_DENSITY_VALUES.has(theme.tokens.density)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.THEME_TOKEN_INVALID,
        `Theme '${theme.name}' has invalid density token '${String(theme.tokens.density)}'.`,
        `${themePath}.tokens.density`,
      ),
    );
  }

  if (!THEME_NAV_VALUES.has(theme.tokens.nav)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.THEME_TOKEN_INVALID,
        `Theme '${theme.name}' has invalid navigation token '${String(theme.tokens.nav)}'.`,
        `${themePath}.tokens.nav`,
      ),
    );
  }
}

function findThemeBaseCycle(theme: ResolvedTheme, indexes: ModelIndexes): string[] | undefined {
  const seen = new Set<string>([theme.name]);
  const path = [theme.name];
  let current: ResolvedTheme | undefined = theme;

  while (current?.base !== undefined) {
    path.push(current.base);
    if (seen.has(current.base)) {
      return path;
    }

    seen.add(current.base);
    current = indexes.themesByName.get(current.base)?.item;
  }

  return undefined;
}

function validateSyncPolicy(
  sync: ResolvedSyncPolicy,
  syncPath: string,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  if (!indexes.objectsByName.has(sync.object)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.SYNC_OBJECT_UNKNOWN,
        `Sync policy references unknown object '${sync.object}'.`,
        `${syncPath}.object`,
      ),
    );
  }

  if (!SYNC_MODES.has(sync.mode)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.SYNC_MODE_INVALID,
        `Sync policy for object '${sync.object}' has invalid mode '${String(sync.mode)}'.`,
        `${syncPath}.mode`,
      ),
    );
  }

  if (!SYNC_SCOPES.has(sync.scope)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.SYNC_SCOPE_INVALID,
        `Sync policy for object '${sync.object}' has invalid scope '${String(sync.scope)}'.`,
        `${syncPath}.scope`,
      ),
    );
  }

  if (!CONFLICT_STRATEGIES.has(sync.conflict)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.SYNC_CONFLICT_INVALID,
        `Sync policy for object '${sync.object}' has invalid conflict strategy '${String(sync.conflict)}'.`,
        `${syncPath}.conflict`,
      ),
    );
  }

  const object = indexes.objectsByName.get(sync.object)?.item;
  if (sync.window !== undefined && object !== undefined) {
    validateSyncWindow(sync.window, object, `${syncPath}.window`, diagnostics, {
      field: MODEL_VALIDATION_CODES.SYNC_WINDOW_FIELD_UNKNOWN,
      fieldType: MODEL_VALIDATION_CODES.SYNC_WINDOW_FIELD_NOT_TEMPORAL,
      days: MODEL_VALIDATION_CODES.SYNC_WINDOW_DAYS_INVALID,
      limit: MODEL_VALIDATION_CODES.SYNC_WINDOW_LIMIT_INVALID,
    });
  }
}

function validateSyncWindow(
  window: ResolvedSyncWindow,
  object: ResolvedObject,
  windowPath: string,
  diagnostics: Diagnostic[],
  codes: {
    field: ModelValidationCode;
    fieldType: ModelValidationCode;
    days: ModelValidationCode;
    limit: ModelValidationCode;
  },
): void {
  const fieldTypes = new Map<string, FieldType>([
    ...object.fields.map((field) => [field.name, field.type] as const),
    ...object.metadataFields.map((field) => [field.name, field.type] as const),
  ]);
  const fieldType = fieldTypes.get(window.field);

  if (fieldType === undefined) {
    diagnostics.push(
      diagnostic(
        codes.field,
        `Sync window field '${window.field}' does not exist on object '${object.name}'.`,
        `${windowPath}.field`,
      ),
    );
  } else if (fieldType !== "date" && fieldType !== "datetime") {
    // A window is a span of days measured against a moment, so the field it
    // names has to hold one. Without this a model could declare a window over
    // any field it liked — `_syncStatus`, say — and get a silently empty
    // dataset, because the runtime parses the value as a date and a value that
    // is not one excludes the record.
    diagnostics.push(
      diagnostic(
        codes.fieldType,
        `Sync window field '${window.field}' on object '${object.name}' is '${fieldType}'; a window must be measured over a date or datetime field.`,
        `${windowPath}.field`,
      ),
    );
  }

  if (window.days !== undefined && !isPositiveInteger(window.days)) {
    diagnostics.push(
      diagnostic(
        codes.days,
        `Sync window days for object '${object.name}' must be a positive integer.`,
        `${windowPath}.days`,
      ),
    );
  }

  if (window.limit !== undefined && !isPositiveInteger(window.limit)) {
    diagnostics.push(
      diagnostic(
        codes.limit,
        `Sync window limit for object '${object.name}' must be a positive integer.`,
        `${windowPath}.limit`,
      ),
    );
  }
}

function validateHookRefs(
  hooks: ResolvedHookRefs,
  hookPath: string,
  diagnostics: Diagnostic[],
): void {
  validateHookRefList(hooks.before, `${hookPath}.before`, diagnostics);
  validateHookRefList(hooks.after, `${hookPath}.after`, diagnostics);
  validateHookRefList(hooks.onError, `${hookPath}.onError`, diagnostics);
}

function validateHookRefList(
  hookRefs: string[],
  hookRefsPath: string,
  diagnostics: Diagnostic[],
): void {
  for (let hookIndex = 0; hookIndex < hookRefs.length; hookIndex += 1) {
    const hookRef = hookRefs[hookIndex];
    if (hookRef === undefined) {
      continue;
    }
    if (!HOOK_REFERENCE_PATTERN.test(hookRef)) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.HOOK_REFERENCE_INVALID,
          `Hook reference '${hookRef}' is not syntactically valid.`,
          `${hookRefsPath}[${hookIndex}]`,
        ),
      );
    }
  }
}

function reportDuplicateNames(
  items: { name: string }[],
  path: string,
  code: ModelValidationCode,
  diagnostics: Diagnostic[],
  message: string,
): void {
  const firstSeen = new Map<string, number>();

  for (let index = 0; index < items.length; index += 1) {
    const item = items[index];
    if (item === undefined) {
      continue;
    }

    const firstIndex = firstSeen.get(item.name);
    if (firstIndex === undefined) {
      firstSeen.set(item.name, index);
      continue;
    }

    diagnostics.push(
      diagnostic(
        code,
        `${message} '${item.name}' also appears at ${path}[${firstIndex}].`,
        `${path}[${index}].name`,
      ),
    );
  }
}

function indexByName<T extends { name: string }>(items: T[]): Map<string, NamedReference<T>> {
  const byName = new Map<string, NamedReference<T>>();

  for (let index = 0; index < items.length; index += 1) {
    const item = items[index];
    if (item === undefined || byName.has(item.name)) {
      continue;
    }
    byName.set(item.name, { item, index });
  }

  return byName;
}

function indexObjectExpressionFields(
  object: ResolvedObject,
): Map<string, NamedReference<ExpressionFieldReference>> {
  const fields = new Map<string, NamedReference<ExpressionFieldReference>>();

  for (const [name, reference] of indexByName(object.fields)) {
    fields.set(name, reference);
  }
  for (const [name, reference] of indexByName(object.computedFields)) {
    fields.set(name, reference);
  }

  return fields;
}

function indexReadModelExpressionFields(
  readModel: ResolvedReadModel,
): Map<string, NamedReference<ExpressionFieldReference>> {
  const fields = new Map<string, NamedReference<ExpressionFieldReference>>();

  for (let fieldIndex = 0; fieldIndex < readModel.fields.length; fieldIndex += 1) {
    const field = readModel.fields[fieldIndex];
    if (field === undefined || fields.has(field.name)) {
      continue;
    }
    fields.set(field.name, {
      item: expressionTypeField(field.name, field.type ?? "text"),
      index: fieldIndex,
    });
  }

  return fields;
}

function commandInputFieldsByName(
  inputs: ResolvedCommandInput[],
): Map<string, NamedReference<ResolvedField>> {
  return indexByName(inputs.map((input) => expressionTypeField(input.name, input.type)));
}

function expressionTypeField(name: string, type: ExpressionStaticType | FieldType): ResolvedField {
  const fieldType: FieldType =
    type === "number" ||
    type === "date" ||
    type === "datetime" ||
    type === "time" ||
    type === "boolean"
      ? type
      : "text";

  return {
    name,
    storageName: name,
    type: fieldType,
    required: false,
    validators: [],
    readonly: false,
    hidden: false,
    systemManaged: false,
  };
}

function expressionTypeToFieldType(type: ExpressionStaticType): FieldType | undefined {
  switch (type) {
    case "text":
    case "number":
    case "date":
    case "datetime":
    case "time":
    case "boolean":
      return type;
    case "null":
    case "unknown":
      return undefined;
  }
}

function isDefaultCompatible(field: ResolvedField, value: unknown): boolean {
  if (!FIELD_TYPES.has(field.type)) {
    return false;
  }

  if (value === null) {
    return !field.required;
  }

  return isValueCompatibleWithFieldType(field.type, value);
}

function isValueCompatibleWithFieldType(type: FieldType, value: unknown): boolean {
  if (!FIELD_TYPES.has(type)) {
    return false;
  }

  if (value === null) {
    return true;
  }

  switch (type) {
    case "text":
    case "date":
    case "datetime":
    case "time":
      return typeof value === "string";
    case "number":
      return typeof value === "number" && Number.isFinite(value);
    case "boolean":
      return typeof value === "boolean";
    case "attachment":
      return typeof value === "string" || isJsonObject(value) || Array.isArray(value);
  }
}

function isJsonObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isPositiveInteger(value: number): boolean {
  return Number.isInteger(value) && value > 0;
}

function diagnostic(
  code: ModelValidationCode,
  message: string,
  path?: string,
  severity: DiagnosticSeverity = "error",
): Diagnostic {
  return {
    severity,
    code,
    message,
    ...(path === undefined ? {} : { path }),
  };
}
