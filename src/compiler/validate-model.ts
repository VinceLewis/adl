function validatePolicy(
  policy: ResolvedPolicy,
  policyIndex: number,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  const policyPath = `policies[${policyIndex}]`;
  const object = indexes.objectsByName.get(policy.object)?.item;

  if (policy.defaultEffect !== "deny") {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.POLICY_DEFAULT_EFFECT_INVALID,
        `Policy '${policy.name}' has invalid default effect '${String(policy.defaultEffect)}'.`,
        `${policyPath}.defaultEffect`,
      ),
    );
  }

  if (object === undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.POLICY_OBJECT_UNKNOWN,
        `Policy '${policy.name}' references unknown object '${policy.object}'.`,
        `${policyPath}.object`,
      ),
    );
    return;
  }

  const fieldsByName = indexByName(object.fields);
  const statesByName =
    object.lifecycle === undefined
      ? new Map<string, NamedReference<unknown>>()
      : indexByName(object.lifecycle.states);
  const actionsByName =
    object.lifecycle === undefined
      ? new Map<string, NamedReference<unknown>>()
      : indexByName(object.lifecycle.actions);

  for (let ruleIndex = 0; ruleIndex < policy.rules.length; ruleIndex += 1) {
    const rule = policy.rules[ruleIndex];
    if (rule === undefined) {
      continue;
    }
    validatePolicyRule(
      rule,
      `${policyPath}.rules[${ruleIndex}]`,
      object,
      fieldsByName,
      statesByName,
      actionsByName,
      indexes,
      diagnostics,
    );
  }
}

function validatePolicyRule(
  rule: ResolvedPolicyRule,
  rulePath: string,
  object: ResolvedObject,
  fieldsByName: Map<string, NamedReference<ResolvedField>>,
  statesByName: Map<string, NamedReference<unknown>>,
  actionsByName: Map<string, NamedReference<unknown>>,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  if (!POLICY_ACTIONS.has(rule.action)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.POLICY_ACTION_INVALID,
        `Policy rule '${rule.name}' has invalid action '${String(rule.action)}'.`,
        `${rulePath}.action`,
      ),
    );
  }

  for (let fieldIndex = 0; fieldIndex < rule.fields.length; fieldIndex += 1) {
    const field = rule.fields[fieldIndex];
    if (field === undefined) {
      continue;
    }
    if (!fieldsByName.has(field)) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.POLICY_FIELD_UNKNOWN,
          `Policy rule '${rule.name}' references unknown field '${field}' on object '${object.name}'.`,
          `${rulePath}.fields[${fieldIndex}]`,
        ),
      );
    }
  }

  for (let stateIndex = 0; stateIndex < rule.state.length; stateIndex += 1) {
    const state = rule.state[stateIndex];
    if (state === undefined) {
      continue;
    }
    if (!statesByName.has(state)) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.POLICY_STATE_UNKNOWN,
          `Policy rule '${rule.name}' references unknown lifecycle state '${state}' on object '${object.name}'.`,
          `${rulePath}.state[${stateIndex}]`,
        ),
      );
    }
  }

  if (rule.lifecycleAction !== undefined && !actionsByName.has(rule.lifecycleAction)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.POLICY_LIFECYCLE_ACTION_UNKNOWN,
        `Policy rule '${rule.name}' references unknown lifecycle action '${rule.lifecycleAction}' on object '${object.name}'.`,
        `${rulePath}.lifecycleAction`,
      ),
    );
  }

  if (rule.condition !== undefined) {
    const conditionType = validateExpression(
      rule.condition,
      `${rulePath}.condition`,
      fieldsByName,
      {
        invalid: MODEL_VALIDATION_CODES.POLICY_CONDITION_INVALID,
        field: MODEL_VALIDATION_CODES.POLICY_CONDITION_FIELD_UNKNOWN,
        runtime: MODEL_VALIDATION_CODES.POLICY_CONDITION_RUNTIME_PROPERTY_INVALID,
        type: MODEL_VALIDATION_CODES.POLICY_CONDITION_TYPE,
      },
      diagnostics,
    );
    if (conditionType !== "boolean" && conditionType !== "unknown") {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.POLICY_CONDITION_TYPE,
          `Policy rule '${rule.name}' condition must resolve to boolean, not ${conditionType}.`,
          `${rulePath}.condition`,
        ),
      );
    }
  }

  for (let channelIndex = 0; channelIndex < rule.channels.length; channelIndex += 1) {
    const channel = rule.channels[channelIndex];
    if (channel === undefined) {
      continue;
    }
    if (!RUNTIME_CHANNELS.has(channel)) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.POLICY_CHANNEL_INVALID,
          `Policy rule '${rule.name}' has invalid runtime channel '${String(channel)}'.`,
          `${rulePath}.channels[${channelIndex}]`,
        ),
      );
    }
  }

  validatePolicyPrincipal(
    rule.principal,
    rule,
    rulePath,
    object,
    fieldsByName,
    indexes,
    diagnostics,
  );
}

/**
 * The `contextMember` principal fails closed at runtime when it cannot resolve a
 * roster, which is right for a request and wrong for a model: a rule that can
 * never match is not a safe default, it is a rule the author believed they had
 * written. A context with no declared membership has no roster to read, so the
 * mismatch is decidable here rather than as an access denial nobody can explain.
 */
function validatePolicyPrincipal(
  principal: ResolvedPrincipalSelector,
  rule: ResolvedPolicyRule,
  rulePath: string,
  object: ResolvedObject,
  fieldsByName: Map<string, NamedReference<ResolvedField>>,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  const principalPath = `${rulePath}.principal`;

  if (principal.match !== "contextMember") {
    if (principal.contextMember !== undefined) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.POLICY_PRINCIPAL_CONTEXT_MEMBER_UNEXPECTED,
          `Policy rule '${rule.name}' declares a context member principal but matches '${String(principal.match)}', so the declaration is never read.`,
          `${principalPath}.contextMember`,
        ),
      );
    }
    return;
  }

  const contextMember = principal.contextMember;
  if (contextMember === undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.POLICY_PRINCIPAL_CONTEXT_MEMBER_MISSING,
        `Policy rule '${rule.name}' matches context members but declares no context member selector.`,
        `${principalPath}.contextMember`,
      ),
    );
    return;
  }

  const context = indexes.contextsByName.get(contextMember.context)?.item;
  if (context === undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.POLICY_PRINCIPAL_CONTEXT_UNKNOWN,
        `Policy rule '${rule.name}' context member principal references unknown business context '${contextMember.context}'.`,
        `${principalPath}.contextMember.context`,
      ),
    );
  } else if (context.membership === undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.POLICY_PRINCIPAL_CONTEXT_MEMBERSHIP_MISSING,
        `Policy rule '${rule.name}' matches members of business context '${contextMember.context}', which declares no membership, so the rule can never match.`,
        `${principalPath}.contextMember.context`,
      ),
    );
  }

  if (!fieldsByName.has(contextMember.field)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.POLICY_PRINCIPAL_CONTEXT_MEMBER_FIELD_UNKNOWN,
        `Policy rule '${rule.name}' context member principal references unknown field '${contextMember.field}' on object '${object.name}'.`,
        `${principalPath}.contextMember.field`,
      ),
    );
  }
}

type ExpressionStaticType = ExpressionValueType | "unknown";

function validateExpression(
  expression: ResolvedExpression,
  expressionPath: string,
  fieldsByName: Map<string, NamedReference<ExpressionFieldReference>>,
  codes: {
    invalid: ModelValidationCode;
    field: ModelValidationCode;
    runtime: ModelValidationCode;
    type: ModelValidationCode;
  },
  diagnostics: Diagnostic[],
): ExpressionStaticType {
  switch (expression.kind) {
    case "literal":
      if (expression.valueType !== undefined) {
        if (!EXPRESSION_VALUE_TYPES.has(expression.valueType)) {
          diagnostics.push(
            diagnostic(
              codes.invalid,
              `Expression literal has invalid value type '${String(expression.valueType)}'.`,
              `${expressionPath}.valueType`,
            ),
          );
          return "unknown";
        }

        if (expression.valueType === "null" && expression.value !== null) {
          diagnostics.push(
            diagnostic(
              codes.type,
              "Expression literal valueType 'null' requires a null value.",
              `${expressionPath}.value`,
            ),
          );
          return "unknown";
        }

        if (
          expression.valueType !== "null" &&
          expression.valueType !== "date" &&
          expression.valueType !== "datetime" &&
          expression.valueType !== "time" &&
          !isValueCompatibleWithExpressionType(expression.valueType, expression.value)
        ) {
          diagnostics.push(
            diagnostic(
              codes.type,
              `Expression literal value is not compatible with ${expression.valueType}.`,
              `${expressionPath}.value`,
            ),
          );
          return "unknown";
        }

        return expression.valueType;
      }

      return expression.value === null
        ? "null"
        : typeof expression.value === "string"
          ? "text"
          : typeof expression.value === "number"
            ? "number"
            : "boolean";
    case "field": {
      const field = fieldsByName.get(expression.field)?.item;
      if (field === undefined) {
        diagnostics.push(
          diagnostic(
            codes.field,
            `Expression references unknown field '${expression.field}'.`,
            `${expressionPath}.field`,
          ),
        );
        return "unknown";
      }
      return field.type === "attachment" ? "unknown" : field.type;
    }
    case "runtime":
      if (!EXPRESSION_RUNTIME_PROPERTIES.has(expression.property)) {
        diagnostics.push(
          diagnostic(
            codes.runtime,
            `Expression references unsupported runtime property '${String(expression.property)}'.`,
            `${expressionPath}.property`,
          ),
        );
        return "unknown";
      }
      return expression.property === "now" ? "datetime" : "text";
    case "unary": {
      if (!EXPRESSION_UNARY_OPERATORS.has(expression.operator)) {
        diagnostics.push(
          diagnostic(
            codes.invalid,
            `Expression has invalid unary operator '${String(expression.operator)}'.`,
            `${expressionPath}.operator`,
          ),
        );
        return "unknown";
      }

      const operandType = validateExpression(
        expression.operand,
        `${expressionPath}.operand`,
        fieldsByName,
        codes,
        diagnostics,
      );
      if (expression.operator === "not") {
        requireExpressionType(
          operandType,
          ["boolean"],
          `${expressionPath}.operand`,
          codes,
          diagnostics,
        );
        return "boolean";
      }
      requireExpressionType(
        operandType,
        ["number"],
        `${expressionPath}.operand`,
        codes,
        diagnostics,
      );
      return "number";
    }
    case "binary":
      return validateBinaryExpression(expression, expressionPath, fieldsByName, codes, diagnostics);
  }

  diagnostics.push(
    diagnostic(
      codes.invalid,
      `Expression has invalid kind '${String((expression as { kind?: unknown }).kind)}'.`,
      `${expressionPath}.kind`,
    ),
  );
  return "unknown";
}

function validateBinaryExpression(
  expression: Extract<ResolvedExpression, { kind: "binary" }>,
  expressionPath: string,
  fieldsByName: Map<string, NamedReference<ExpressionFieldReference>>,
  codes: {
    invalid: ModelValidationCode;
    field: ModelValidationCode;
    runtime: ModelValidationCode;
    type: ModelValidationCode;
  },
  diagnostics: Diagnostic[],
): ExpressionStaticType {
  if (!EXPRESSION_BINARY_OPERATORS.has(expression.operator)) {
    diagnostics.push(
      diagnostic(
        codes.invalid,
        `Expression has invalid binary operator '${String(expression.operator)}'.`,
        `${expressionPath}.operator`,
      ),
    );
    return "unknown";
  }

  const leftType = validateExpression(
    expression.left,
    `${expressionPath}.left`,
    fieldsByName,
    codes,
    diagnostics,
  );
  const rightType = validateExpression(
    expression.right,
    `${expressionPath}.right`,
    fieldsByName,
    codes,
    diagnostics,
  );

  switch (expression.operator) {
    case "+":
    case "-":
    case "*":
    case "/":
      requireExpressionType(leftType, ["number"], `${expressionPath}.left`, codes, diagnostics);
      requireExpressionType(rightType, ["number"], `${expressionPath}.right`, codes, diagnostics);
      return "number";
    case "and":
    case "or":
      requireExpressionType(leftType, ["boolean"], `${expressionPath}.left`, codes, diagnostics);
      requireExpressionType(rightType, ["boolean"], `${expressionPath}.right`, codes, diagnostics);
      return "boolean";
    case "==":
    case "!=":
      if (
        leftType !== "unknown" &&
        rightType !== "unknown" &&
        leftType !== "null" &&
        rightType !== "null" &&
        leftType !== rightType
      ) {
        diagnostics.push(
          diagnostic(
            codes.type,
            `Expression compares incompatible types ${leftType} and ${rightType}.`,
            expressionPath,
          ),
        );
      }
      return "boolean";
    case "<":
    case "<=":
    case ">":
    case ">=":
      if (
        !areComparableExpressionTypes(leftType, rightType) &&
        leftType !== "unknown" &&
        rightType !== "unknown"
      ) {
        diagnostics.push(
          diagnostic(
            codes.type,
            `Expression cannot compare ${leftType} with ${rightType}.`,
            expressionPath,
          ),
        );
      }
      return "boolean";
    case "in":
      diagnostics.push(
        diagnostic(
          codes.invalid,
          "Expression operator 'in' is reserved until list expressions are added.",
          `${expressionPath}.operator`,
        ),
      );
      return "boolean";
    case "??":
      return leftType === "null" ? rightType : leftType;
  }
}

function requireExpressionType(
  actual: ExpressionStaticType,
  expected: ExpressionStaticType[],
  path: string,
  codes: { type: ModelValidationCode },
  diagnostics: Diagnostic[],
): void {
  if (actual === "unknown" || expected.includes(actual)) {
    return;
  }

  diagnostics.push(
    diagnostic(
      codes.type,
      `Expression expected ${expected.join(" or ")} but received ${actual}.`,
      path,
    ),
  );
}

function areComparableExpressionTypes(
  left: ExpressionStaticType,
  right: ExpressionStaticType,
): boolean {
  return (
    left === right &&
    (left === "number" ||
      left === "text" ||
      left === "date" ||
      left === "datetime" ||
      left === "time")
  );
}

function isValueCompatibleWithExpressionType(type: ExpressionValueType, value: unknown): boolean {
  switch (type) {
    case "text":
    case "date":
    case "datetime":
    case "time":
      return typeof value === "string";
    case "number":
      return typeof value === "number" && Number.isFinite(value);
    case "boolean":
      return typeof value === "boolean";
    case "null":
      return value === null;
  }
}

function validateView(
  view: ResolvedView,
  viewPath: string,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  const targetObject = indexes.objectsByName.get(view.object)?.item;

  if (!VIEW_KINDS.has(view.kind)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.VIEW_KIND_INVALID,
        `View has invalid kind '${String(view.kind)}'.`,
        `${viewPath}.kind`,
      ),
    );
  }

  validateViewContext(view.context, `${viewPath}.context`, indexes, diagnostics);
  validateEditContainerMode(view.editContainer, `${viewPath}.editContainer`, diagnostics);

  if (targetObject === undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.VIEW_OBJECT_UNKNOWN,
        `View references unknown object '${view.object}'.`,
        `${viewPath}.object`,
      ),
    );
    return;
  }

  const readModel =
    view.readModel === undefined ? undefined : indexes.readModelsByName.get(view.readModel)?.item;
  if (view.readModel !== undefined && readModel === undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.VIEW_READ_MODEL_UNKNOWN,
        `View '${view.name}' references unknown read model '${view.readModel}'.`,
        `${viewPath}.readModel`,
      ),
    );
  }

  const fieldNames =
    readModel === undefined
      ? new Set([
          ...targetObject.fields.map((field) => field.name),
          ...targetObject.computedFields.map((field) => field.name),
        ])
      : new Set(readModel.fields.map((field) => field.name));
  const fieldOwner =
    readModel === undefined ? `object '${targetObject.name}'` : `read model '${readModel.name}'`;

  for (let fieldIndex = 0; fieldIndex < view.fields.length; fieldIndex += 1) {
    const field = view.fields[fieldIndex];
    if (field === undefined) {
      continue;
    }
    if (!fieldNames.has(field)) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.VIEW_FIELD_UNKNOWN,
          `View references unknown field '${field}' on ${fieldOwner}.`,
          `${viewPath}.fields[${fieldIndex}]`,
        ),
      );
    }
  }

  for (let fieldIndex = 0; fieldIndex < view.searchFields.length; fieldIndex += 1) {
    const field = view.searchFields[fieldIndex];
    if (field === undefined) {
      continue;
    }
    if (!fieldNames.has(field)) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.VIEW_SEARCH_FIELD_UNKNOWN,
          `View references unknown search field '${field}' on ${fieldOwner}.`,
          `${viewPath}.searchFields[${fieldIndex}]`,
        ),
      );
    }
  }

  for (let sortIndex = 0; sortIndex < view.sort.length; sortIndex += 1) {
    const sortItem = view.sort[sortIndex];
    if (sortItem === undefined) {
      continue;
    }
    if (!fieldNames.has(sortItem.field)) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.VIEW_SORT_FIELD_UNKNOWN,
          `View references unknown sort field '${sortItem.field}' on ${fieldOwner}.`,
          `${viewPath}.sort[${sortIndex}].field`,
        ),
      );
    }
  }

  validateViewEditSections(
    view.editSections,
    `${viewPath}.editSections`,
    targetObject,
    fieldNames,
    new Set(view.fields),
    indexes,
    diagnostics,
  );

  if (view.presentation !== undefined) {
    validateViewPresentation(view.presentation, view, viewPath, targetObject, indexes, diagnostics);
  }
}

function validateViewEditSections(
  sections: ResolvedEditSection[],
  sectionsPath: string,
  parentObject: ResolvedObject,
  parentFieldNames: Set<string>,
  viewFields: Set<string>,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  reportDuplicateNames(
    sections,
    sectionsPath,
    MODEL_VALIDATION_CODES.VIEW_EDIT_SECTION_DUPLICATE,
    diagnostics,
    `Edit section names must be unique within object '${parentObject.name}' views.`,
  );

  for (let sectionIndex = 0; sectionIndex < sections.length; sectionIndex += 1) {
    const section = sections[sectionIndex];
    if (section === undefined) {
      continue;
    }

    const sectionPath = `${sectionsPath}[${sectionIndex}]`;
    if (!EDIT_SECTION_KINDS.has(section.kind)) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.VIEW_EDIT_SECTION_KIND_INVALID,
          `Edit section '${section.name}' has invalid kind '${String(section.kind)}'.`,
          `${sectionPath}.kind`,
        ),
      );
      continue;
    }

    if (section.kind === "fields") {
      for (let fieldIndex = 0; fieldIndex < section.fields.length; fieldIndex += 1) {
        const field = section.fields[fieldIndex];
        if (field === undefined || parentFieldNames.has(field)) {
          continue;
        }
        if (viewFields.has(field)) {
          continue;
        }

        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.VIEW_EDIT_SECTION_FIELD_UNKNOWN,
            `Edit field section '${section.name}' references unknown field '${field}' on object '${parentObject.name}'.`,
            `${sectionPath}.fields[${fieldIndex}]`,
          ),
        );
      }
      continue;
    }

    const childObject = indexes.objectsByName.get(section.childObject)?.item;
    if (childObject === undefined) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.VIEW_EDIT_SECTION_CHILD_OBJECT_UNKNOWN,
          `Edit child collection '${section.name}' references unknown child object '${section.childObject}'.`,
          `${sectionPath}.childObject`,
        ),
      );
    } else {
      const parentField = childObject.fields.find((field) => field.name === section.parentField);
      if (parentField === undefined) {
        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.VIEW_EDIT_SECTION_PARENT_FIELD_UNKNOWN,
            `Edit child collection '${section.name}' references unknown parent field '${section.parentField}' on child object '${childObject.name}'.`,
            `${sectionPath}.parentField`,
          ),
        );
      } else if (parentField.lookup?.targetObject !== parentObject.name) {
        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.VIEW_EDIT_SECTION_PARENT_FIELD_INVALID,
            `Edit child collection '${section.name}' parent field '${section.parentField}' must lookup parent object '${parentObject.name}'.`,
            `${sectionPath}.parentField`,
          ),
        );
      }

      /*
       * `unlink` detaches a child by clearing its lookup back to the parent, so
       * a required parent field can never honour it: the write the operation
       * plans is refused by the child object's own validation. The language
       * could declare it and the model could not satisfy it, with nothing
       * saying why until a user clicked the control.
       */
      if (
        parentField !== undefined &&
        parentField.required &&
        section.operations.includes("unlink")
      ) {
        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.VIEW_EDIT_SECTION_UNLINK_PARENT_FIELD_REQUIRED,
            `Edit child collection '${section.name}' supports 'unlink' but parent field '${section.parentField}' on child object '${childObject.name}' is required, so a child can never be detached from its parent. Use 'remove' instead, or make the field optional.`,
            `${sectionPath}.operations`,
          ),
        );
      }

      if (section.childView !== undefined) {
        const childView = childObject.views.find((view) => view.name === section.childView);
        if (childView === undefined) {
          diagnostics.push(
            diagnostic(
              MODEL_VALIDATION_CODES.VIEW_EDIT_SECTION_CHILD_VIEW_UNKNOWN,
              `Edit child collection '${section.name}' references unknown child view '${section.childView}' on object '${childObject.name}'.`,
              `${sectionPath}.childView`,
            ),
          );
        }
      }

      if (
        section.orderField !== undefined &&
        !childObject.fields.some((field) => field.name === section.orderField)
      ) {
        diagnostics.push(
          diagnostic(
            MODEL_VALIDATION_CODES.VIEW_EDIT_SECTION_ORDER_FIELD_UNKNOWN,
            `Edit child collection '${section.name}' references unknown order field '${section.orderField}' on child object '${childObject.name}'.`,
            `${sectionPath}.orderField`,
          ),
        );
      }

      if (section.picker !== undefined) {
        validateRelationshipPicker(
          section.picker,
          `${sectionPath}.picker`,
          section,
          childObject,
          indexes,
          diagnostics,
        );
      }
    }

    for (let operationIndex = 0; operationIndex < section.operations.length; operationIndex += 1) {
      const operation = section.operations[operationIndex];
      if (operation === undefined || EDIT_CHILD_OPERATION_KINDS.has(operation)) {
        continue;
      }

      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.VIEW_EDIT_SECTION_OPERATION_INVALID,
          `Edit child collection '${section.name}' has unsupported operation '${String(operation)}'.`,
          `${sectionPath}.operations[${operationIndex}]`,
        ),
      );
    }

    if (section.operations.includes("reorder") && section.orderField === undefined) {
      diagnostics.push(
        diagnostic(
          MODEL_VALIDATION_CODES.VIEW_EDIT_SECTION_ORDER_FIELD_UNKNOWN,
          `Edit child collection '${section.name}' requires orderField when reorder is supported.`,
          `${sectionPath}.orderField`,
        ),
      );
    }
  }
}

function validateRelationshipPicker(
  picker: ResolvedRelationshipPicker,
  pickerPath: string,
  section: Extract<ResolvedEditSection, { kind: "childCollection" }>,
  childObject: ResolvedObject,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): void {
  /*
   * A picker naming a candidate field creates children; one without links
   * existing ones. They therefore need different operations declared, and
   * requiring `linkExisting` of a minting picker would refuse the very
   * declaration this exists to allow.
   */
  const candidateTarget = validateRelationshipPickerCandidateField(
    picker,
    pickerPath,
    childObject,
    diagnostics,
  );
  const mints = picker.candidateField !== undefined;

  if (mints && !section.operations.includes("createChild")) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.RELATIONSHIP_PICKER_CREATE_OPERATION_REQUIRED,
        `Relationship picker '${picker.name}' names candidate field '${String(picker.candidateField)}', so edit child collection '${section.name}' must support createChild.`,
        `${pickerPath}.name`,
      ),
    );
  }

  if (!mints && !section.operations.includes("linkExisting")) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.RELATIONSHIP_PICKER_LINK_OPERATION_REQUIRED,
        `Relationship picker '${picker.name}' requires edit child collection '${section.name}' to support linkExisting.`,
        `${pickerPath}.name`,
      ),
    );
  }

  if (!RELATIONSHIP_PICKER_SOURCE_KINDS.has(picker.sourceKind)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.RELATIONSHIP_PICKER_SOURCE_KIND_INVALID,
        `Relationship picker '${picker.name}' has invalid source kind '${String(picker.sourceKind)}'.`,
        `${pickerPath}.sourceKind`,
      ),
    );
    return;
  }

  if (!RELATIONSHIP_PICKER_SELECTION_MODES.has(picker.selection)) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.RELATIONSHIP_PICKER_SELECTION_INVALID,
        `Relationship picker '${picker.name}' has invalid selection mode '${String(picker.selection)}'.`,
        `${pickerPath}.selection`,
      ),
    );
  }

  const fields =
    picker.sourceKind === "object"
      ? validateObjectRelationshipPickerSource(
          picker,
          pickerPath,
          mints ? candidateTarget : childObject.name,
          indexes,
          diagnostics,
        )
      : validateReadModelRelationshipPickerSource(
          picker,
          pickerPath,
          mints ? candidateTarget : childObject.name,
          indexes,
          diagnostics,
        );

  if (fields === undefined) {
    return;
  }

  for (let fieldIndex = 0; fieldIndex < picker.displayFields.length; fieldIndex += 1) {
    const field = picker.displayFields[fieldIndex];
    if (field === undefined || fields.has(field)) {
      continue;
    }

    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.RELATIONSHIP_PICKER_DISPLAY_FIELD_UNKNOWN,
        `Relationship picker '${picker.name}' displays unknown candidate field '${field}'.`,
        `${pickerPath}.displayFields[${fieldIndex}]`,
      ),
    );
  }

  for (let fieldIndex = 0; fieldIndex < picker.searchFields.length; fieldIndex += 1) {
    const field = picker.searchFields[fieldIndex];
    if (field === undefined || fields.has(field)) {
      continue;
    }

    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.RELATIONSHIP_PICKER_SEARCH_FIELD_UNKNOWN,
        `Relationship picker '${picker.name}' searches unknown candidate field '${field}'.`,
        `${pickerPath}.searchFields[${fieldIndex}]`,
      ),
    );
  }

  for (let sortIndex = 0; sortIndex < picker.sort.length; sortIndex += 1) {
    const sort = picker.sort[sortIndex];
    if (sort === undefined || fields.has(sort.field)) {
      continue;
    }

    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.RELATIONSHIP_PICKER_SORT_FIELD_UNKNOWN,
        `Relationship picker '${picker.name}' sorts by unknown candidate field '${sort.field}'.`,
        `${pickerPath}.sort[${sortIndex}].field`,
      ),
    );
  }
}

/**
 * The child field a minting picker writes its chosen candidate into, and the
 * object those candidates must therefore come from.
 *
 * Returns the field's lookup target, or `undefined` when there is nothing sound
 * to check the source against — either because the picker links rather than
 * mints, or because the field itself is already wrong and reporting a second
 * failure about its target would only bury the first.
 */
function validateRelationshipPickerCandidateField(
  picker: ResolvedRelationshipPicker,
  pickerPath: string,
  childObject: ResolvedObject,
  diagnostics: Diagnostic[],
): string | undefined {
  if (picker.candidateField === undefined) {
    return undefined;
  }

  const field = childObject.fields.find((candidate) => candidate.name === picker.candidateField);
  if (field === undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.RELATIONSHIP_PICKER_CANDIDATE_FIELD_UNKNOWN,
        `Relationship picker '${picker.name}' references unknown candidate field '${picker.candidateField}' on child object '${childObject.name}'.`,
        `${pickerPath}.candidateField`,
      ),
    );
    return undefined;
  }

  if (field.lookup === undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.RELATIONSHIP_PICKER_CANDIDATE_FIELD_INVALID,
        `Relationship picker '${picker.name}' candidate field '${field.name}' must be a lookup field, because the picker writes a chosen record's id into it.`,
        `${pickerPath}.candidateField`,
      ),
    );
    return undefined;
  }

  return field.lookup.targetObject;
}

function validateObjectRelationshipPickerSource(
  picker: ResolvedRelationshipPicker,
  pickerPath: string,
  requiredObjectName: string | undefined,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): Set<string> | undefined {
  const source = indexes.objectsByName.get(picker.source)?.item;
  if (source === undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.RELATIONSHIP_PICKER_SOURCE_UNKNOWN,
        `Relationship picker '${picker.name}' references unknown object source '${picker.source}'.`,
        `${pickerPath}.source`,
      ),
    );
    return undefined;
  }

  if (requiredObjectName !== undefined && source.name !== requiredObjectName) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.RELATIONSHIP_PICKER_SOURCE_UNKNOWN,
        `Relationship picker '${picker.name}' object source '${picker.source}' must be '${requiredObjectName}'.`,
        `${pickerPath}.source`,
      ),
    );
  }

  return new Set(indexObjectExpressionFields(source).keys());
}

function validateReadModelRelationshipPickerSource(
  picker: ResolvedRelationshipPicker,
  pickerPath: string,
  requiredObjectName: string | undefined,
  indexes: ModelIndexes,
  diagnostics: Diagnostic[],
): Set<string> | undefined {
  const readModel = indexes.readModelsByName.get(picker.source)?.item;
  if (readModel === undefined) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.RELATIONSHIP_PICKER_SOURCE_UNKNOWN,
        `Relationship picker '${picker.name}' references unknown read model source '${picker.source}'.`,
        `${pickerPath}.source`,
      ),
    );
    return undefined;
  }

  if (
    requiredObjectName !== undefined &&
    !readModel.sources.some((source) => source.object === requiredObjectName)
  ) {
    diagnostics.push(
      diagnostic(
        MODEL_VALIDATION_CODES.RELATIONSHIP_PICKER_SOURCE_UNKNOWN,
        `Relationship picker '${picker.name}' read model '${picker.source}' must include '${requiredObjectName}' as a source.`,
        `${pickerPath}.source`,
      ),
    );
  }

  return new Set(readModel.fields.map((field) => field.name));
}

